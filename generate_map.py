def get_color(morbidity):
    if morbidity >= LEVEL_HIGH_MIN:
        return '#8B0000'
    elif morbidity >= LEVEL_MEDIUM_MIN:
        return '#FFA500'
    else:
        return '#90EE90'


def get_level(morbidity):
    if morbidity >= LEVEL_HIGH_MIN:
        return 'Высокий'
    elif morbidity >= LEVEL_MEDIUM_MIN:
        return 'Средний'
    else:
        return 'Низкий'


def load_geojson():
    """Загружает GeoJSON данные из файла"""
    possible_names = [
        'Воронежская область_Voronezh.txt',
        'Voronezh_obl.geojson.txt',
        'voronezh_districts.geojson'
    ]

    for name in possible_names:
        file_path = Path(name)
        if file_path.exists():
            with open(file_path, 'r', encoding='utf-8') as f:
                print(f"✅ Найден файл: {name}")
                return json.load(f)
    return None


